# -*- coding: utf-8 -*-
"""放宽「一句话核心观点」口径（2026-10-19 用户要求）。

【用户要求】方向/置信度纵向排列后空间变大，观点口径可以更丰富、字数适当提升。
【改法】只改 prompt 侧的写作要求（不改数据层、不改解析层）：
        ① 从"精炼一句话(约 20~30 字)"放宽到"一段完整判断 60~120 字(2~3 个分句)"；
        ② 明确要求写"核心驱动 + 结论/分歧点"，禁止空话与逐家拼接；
        ③ 补充"不要在单元格内使用竖线 |"（观点变长后命中概率上升，而 markdown 解析
           `line.strip('|').split('|')` 在前 ⇒ 含竖线会把**整行切碎**，`replace` 事后救不了）；
        ④ 总篇幅 2400 → 3200 字（21 品种 × 增加约 80 字）。
【EOL】web_app.py 为 CRLF，读写须归一化并自检。
"""
from pathlib import Path

P = Path("web_app.py")
raw = P.read_bytes()
assert raw.count(b"\r\n") > 0 and raw.count(b"\n") == raw.count(b"\r\n"), "EOL 非纯 CRLF"
t = raw.decode("utf-8").replace("\r\n", "\n")

applied = []


def sub(old, new, label):
    global t
    n = t.count(old)
    assert n == 1, "★ [%s] 锚点命中 %d 次" % (label, n)
    t = t.replace(old, new, 1)
    applied.append(label)


OLD_1 = '''        "【重点1】「一句话核心观点」请用精炼一句话概括该品种当日各家逻辑的共识或分歧"
        "(如「供增需减兑现、冲高回落,均关注海峡通行与进口回升」),不要罗列数据;\\n"'''
NEW_1 = '''        "【重点1】「一句话核心观点」写成**一段完整判断(60~120 字, 2~3 个分句)**:"
        "先点明核心驱动(供给/需求/成本/库存/政策等**具体变量**如何变化),再给结论(方向与节奏);"
        "多家机构存在分歧时,点明分歧落在哪个变量上"
        "(如「供增需减兑现、冲高回落;均关注海峡通行与进口回升,分歧在于投产节奏」)。"
        "要求:可回溯到材料原文、不罗列行情数字、不写空话套话"
        "(「需关注后市」「谨慎观望」「多空交织」单独成句即属套话, 必须跟在具体驱动后面);"
        "严禁用分号把各家原文逐条拼接(那是罗列, 不是提炼);"
        "**单元格内严禁出现竖线 |** (会切断 markdown 表格的列);\\n"'''
sub(OLD_1, NEW_1, "① 重点1 观点口径 60~120 字 + 禁竖线")

# 总篇幅：观点列每行多约 80 字 ⇒ 21 行多约 1700 字，2400 不够
OLD_2 = '"第二节为表格化逐家对比,总篇幅放宽到 2400 字左右。\\n"'
NEW_2 = '"第二节为表格化逐家对比,总篇幅放宽到 3200 字左右(总表观点口径已放宽到 60~120 字)。\\n"'
sub(OLD_2, NEW_2, "② 总篇幅 2400 → 3200")

out = t.replace("\n", "\r\n").encode("utf-8")
assert out.count(b"\n") == out.count(b"\r\n"), "出口 EOL 破坏"
P.write_bytes(out)
print("  已应用 %d 处：" % len(applied))
for x in applied:
    print("   ✔", x)
