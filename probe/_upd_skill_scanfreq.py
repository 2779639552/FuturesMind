"""给 skill 的 W-7e 补三条可复用判据（2026-10-16）：
   ① 扫码频率的比较判据；② 「扫码即采」解耦；③ 空闲超时 vs 绝对 TTL 的决定性实验。
⚠ 用脚本文件写，避免 heredoc 吃转义（本轮已踩三次）。
"""
from pathlib import Path

P = Path(r"C:/Users/lenovo/.workbuddy/skills/silent-pipeline-failure-triage/SKILL.md")
raw = P.read_bytes()
eol = "\r\n" if raw.count(b"\r\n") > 0 else "\n"
s = raw.decode("utf-8")

ANCHOR = "#### ★ 两个落地细节"
assert s.count(ANCHOR) == 1, ("anchor", s.count(ANCHOR))
assert "扫码频率的比较判据" not in s, "已补过"

BLOCK = """#### ★★★ 扫码频率没有固定答案，只有一条比较

> **扫码频率由「一次扫码能撑多久」与「两次运行之间的静默间隔」谁更大决定。**
> 间隔 > 寿命 ⇒ **每次运行前都得重扫** ⇒ 自动化不可行。
> （本项目：定时轮 08:30 / 18:30 ⇒ 间隔 **10h / 14h**；而会话 **8h 内已死**
> ⇒ 每天至少两次，且得"正好在运行前扫"。）

**把这条算成数字再跟用户谈**，比说"可能会比较频繁"有用得多：
列出"运行时刻 → 间隔"，再给"实测寿命（哪怕是区间）"，结论自然出来。

#### ★★★ 解耦：把「定时轮」改成「扫码即采」

既然必须人工扫码，就**别让时钟决定何时采集** —— 改成「**扫码完成后立刻采一次**」：
- 采集频率 = 用户想要的**数据新鲜度**，而不是被会话寿命牵着走；
- 不再产生"定时轮又失败"这种**没有行动价值**的告警。

⇒ 这是"借来的会话"类通道唯一体面的自动化形态（其余按方案 A/C 走）。

#### ★★★ 决定性未知：会话超时是「空闲超时」还是「绝对 TTL」

这直接决定"保活"能不能救回全自动：

| 类型 | 保活心跳能否续命 | 结论 |
|---|---|---|
| **空闲超时**（一段时间无请求才失效） | **可能**（每 20~30 分钟打一次便宜的已认证请求） | 方案 B 可行，全自动能回来 |
| **绝对 TTL**（到点必失效，与活动无关） | 无用 | 方案 B 无望 ⇒ 转官方网关 |

**测法**：重登后让探针每 **10~15 分钟**打一次（不是"等到失效再打"，而是**持续打**）。
远超原寿命仍活着 ⇒ 倾向空闲超时（同时这一行为本身就是**保活原型**）；
若仍到点就死 ⇒ 绝对 TTL。
⚠ 间隔不能太密：这类私域接口常见"单次不限频、**频繁轮询会被判异常**"。

#### ★ 两个落地细节"""

s = s.replace(ANCHOR, BLOCK, 1)
s = s.replace("\r\n", "\n").replace("\n", eol)
P.write_bytes(s.encode("utf-8"))
b = P.read_bytes()
print("  ✔ skill 已更新；EOL: CRLF=%d bareLF=%d；总行数 %d"
      % (b.count(b"\r\n"), b.count(b"\n") - b.count(b"\r\n"), s.count("\r\n") + 1))
